create table author
(
    id   bigint generated by default as identity primary key,
    name varchar(255) not null,

    -- по имени ищем автора при импорте
    constraint author_name_uq unique (name)
);

create table book
(
    id             bigint generated by default as identity primary key,
    title          varchar(255) not null,
    author_id      bigint       not null,
    genre          varchar(32)  not null,
    published_year int          not null,

    constraint book_author_fk foreign key (author_id) references author (id),
    constraint book_genre_chk check (genre in ('NOVEL', 'NOVELLA', 'POETRY', 'DRAMA', 'FANTASY'))
);

create index book_author_id_idx on book (author_id);
